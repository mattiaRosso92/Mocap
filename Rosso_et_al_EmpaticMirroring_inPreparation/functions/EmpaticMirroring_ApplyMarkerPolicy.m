function [coordinates,labels,policy] = ...
    EmpaticMirroring_ApplyMarkerPolicy( ...
    coordinates,labels,sampleRate,config,analysisSampleIndices)
%EMPATICMIRRORING_APPLYMARKERPOLICY Create the full analysis marker space.
%   Raw markers are reordered to the canonical 22-marker skeleton. Gap
%   interpolation is delegated completely to FREQNESS_InterpolateGaps_Mocap
%   so this study does not maintain a second reconstruction implementation.
%   Every reconstructed sample remains identified for exclusion from
%   FREQ-NESS and downstream time-resolved analyses.

if nargin < 4 || isempty(config)
    config = EmpaticMirroring_Config();
end
if ~isnumeric(coordinates) || ~ismatrix(coordinates) || ...
        mod(size(coordinates,1),3) ~= 0
    error('EmpaticMirroring:MarkerPolicyCoordinateShape', ...
        'Coordinates must be [3*markers x time].');
end
if ~isnumeric(sampleRate) || ~isscalar(sampleRate) || ...
        ~isfinite(sampleRate) || sampleRate <= 0
    error('EmpaticMirroring:MarkerPolicySampleRate', ...
        'sampleRate must be a positive finite scalar.');
end
if nargin < 5 || isempty(analysisSampleIndices)
    analysisSampleIndices = 1:size(coordinates,2);
end
if ~isnumeric(analysisSampleIndices) || ...
        ~isvector(analysisSampleIndices) || ...
        any(~isfinite(analysisSampleIndices)) || ...
        any(analysisSampleIndices ~= round(analysisSampleIndices)) || ...
        any(analysisSampleIndices < 1) || ...
        any(analysisSampleIndices > size(coordinates,2)) || ...
        any(diff(analysisSampleIndices) ~= 1)
    error('EmpaticMirroring:MarkerPolicyAnalysisSamples', ...
        'analysisSampleIndices must be one contiguous valid sample range.');
end
analysisSampleIndices = double(analysisSampleIndices(:)');

sourceLabels = normalizeMarkerLabels(labels);
targetLabels = string(config.markers.labels(:));
if numel(sourceLabels) ~= size(coordinates,1)/3
    error('EmpaticMirroring:MarkerPolicyLabelCount', ...
        'Marker-label count does not match the coordinate array.');
end
[matched,markerOrder] = ismember(lower(targetLabels),lower(sourceLabels));
if ~all(matched) || numel(unique(markerOrder)) ~= numel(markerOrder)
    missingLabels = targetLabels(~matched);
    error('EmpaticMirroring:MarkerPolicyMismatch', ...
        'Recording lacks required analysis markers: %s.', ...
        strjoin(missingLabels,', '));
end

coordinateOrder = reshape(3*markerOrder(:)' + (-2:0)',1,[]);
coordinates = coordinates(coordinateOrder,:);
labels = targetLabels;

[coordinates,~,gapInfo] = FREQNESS_InterpolateGaps_Mocap( ...
    coordinates,sampleRate, ...
    'maximum_interpolated_gap', ...
    config.preprocessing.shortGapInterpolationSeconds, ...
    'maximum_reconstructed_gap', ...
    config.preprocessing.maximumReconstructedGapSeconds, ...
    'required_samples',analysisSampleIndices, ...
    'boundary_method',config.preprocessing.boundaryMethod);
coordinates = coordinates(:,analysisSampleIndices);
gapInfo = restrictGapInfo(gapInfo,analysisSampleIndices);
nSamples = size(coordinates,2);
originalMissingMask = gapInfo.bad_marker_sample_mask;
badSegments = gapInfo.bad_segments;
unresolvedMask = gapInfo.unresolved_marker_sample_mask;
unresolvedLabels = labels(any(unresolvedMask,2));
policy = struct( ...
    'version',string(config.markers.policyVersion), ...
    'labels',labels, ...
    'originalMissingMask',originalMissingMask, ...
    'originalBadSampleMask',ismember(1:nSamples,badSegments), ...
    'interpolatedMask',gapInfo.interpolated_marker_sample_mask, ...
    'interpolatedSampleCount', ...
    nnz(gapInfo.interpolated_marker_sample_mask), ...
    'reconstructedMask',gapInfo.reconstructed_marker_sample_mask, ...
    'reconstructedSampleCount', ...
    nnz(gapInfo.reconstructed_marker_sample_mask), ...
    'filledMask',gapInfo.interpolated_marker_sample_mask | ...
    gapInfo.reconstructed_marker_sample_mask, ...
    'filledSampleCount',nnz(gapInfo.interpolated_marker_sample_mask | ...
    gapInfo.reconstructed_marker_sample_mask), ...
    'unresolvedMask',unresolvedMask, ...
    'unresolvedBadSampleMask',any(unresolvedMask,1), ...
    'unresolvedMarkerLabels',unresolvedLabels, ...
    'maximumInterpolatedGapFrames',gapInfo.maximum_interpolated_gap_frames, ...
    'maximumInterpolatedGapMilliseconds', ...
    1000*gapInfo.maximum_interpolated_gap_frames/sampleRate, ...
    'maximumReconstructedGapFrames', ...
    gapInfo.maximum_reconstructed_gap_frames, ...
    'maximumReconstructedGapMilliseconds', ...
    1000*gapInfo.maximum_reconstructed_gap_frames/sampleRate, ...
    'completeTimepointFraction',mean(~any(originalMissingMask,1)), ...
    'reconstructionMethod',string( ...
    config.preprocessing.reconstructionMethod), ...
    'gapInfo',gapInfo, ...
    'isEligible',~any(unresolvedMask,'all'));

end


function gapInfo = restrictGapInfo(gapInfo,indices)

coordinateFields = {'original_missing_coordinate_mask'};
markerFields = {'bad_marker_sample_mask', ...
    'interpolated_marker_sample_mask', ...
    'reconstructed_marker_sample_mask', ...
    'unresolved_marker_sample_mask'};
for fieldIndex = 1:numel(coordinateFields)
    name = coordinateFields{fieldIndex};
    gapInfo.(name) = gapInfo.(name)(:,indices);
end
for fieldIndex = 1:numel(markerFields)
    name = markerFields{fieldIndex};
    gapInfo.(name) = gapInfo.(name)(:,indices);
end
gapInfo.bad_segments = find(any(gapInfo.bad_marker_sample_mask,1));
gapInfo.bad_segments_by_participant = {gapInfo.bad_segments};
gapInfo.required_samples = 1:numel(indices);
gapInfo.missing_coordinate_sample_count = ...
    nnz(gapInfo.original_missing_coordinate_mask);
gapInfo.affected_marker_sample_count = ...
    nnz(gapInfo.bad_marker_sample_mask);
gapInfo.affected_timepoint_count = numel(gapInfo.bad_segments);
gapInfo.has_gaps = ~isempty(gapInfo.bad_segments);

end


function labels = normalizeMarkerLabels(labels)

labels = regexprep(strtrim(string(labels(:))),'\s+',' ');
normalized = lower(labels);
aliases = [ ...
    "strainum", "sternum"; ...
    "r should", "r shoulder"; ...
    "l ankel", "l ankle"; ...
    "r ankel", "r ankle"; ...
    "f head", "t head"];
for aliasIndex = 1:size(aliases,1)
    normalized(normalized == aliases(aliasIndex,1)) = ...
        aliases(aliasIndex,2);
end
if numel(unique(normalized)) ~= numel(normalized)
    error('EmpaticMirroring:DuplicateCanonicalMarker', ...
        'Marker aliases produce duplicate canonical labels.');
end

labels = strings(size(normalized));
for labelIndex = 1:numel(normalized)
    words = split(normalized(labelIndex)," ");
    for wordIndex = 1:numel(words)
        word = char(words(wordIndex));
        if ~isempty(word)
            word(1) = upper(word(1));
        end
        words(wordIndex) = string(word);
    end
    labels(labelIndex) = strjoin(words," ");
end

end
