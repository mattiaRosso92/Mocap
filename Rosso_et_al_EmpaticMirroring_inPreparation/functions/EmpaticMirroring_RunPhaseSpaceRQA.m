function [dyadManifest,summary] = EmpaticMirroring_RunPhaseSpaceRQA( ...
    dyadManifest,config)
%EMPATICMIRRORING_RUNPHASESPACERQA Run BLOCK 4 phase-space RQA.
%   This is the DyadicDance phase-space temporal-coordination analysis,
%   stored per participant recording and component with compact summaries.

validateBlock4Inputs(dyadManifest,config);
if ~isfolder(config.block4.output_path)
    mkdir(config.block4.output_path);
end

coreFiles = resolveCoreFiles(dyadManifest);
eligibleRows = find(strlength(coreFiles) > 0 & isfile(coreFiles));
if isfinite(config.block4.max_dyads)
    eligibleRows = eligibleRows(1:min( ...
        numel(eligibleRows),config.block4.max_dyads));
end
if isempty(eligibleRows)
    error('EmpaticMirroring:PhaseRQAMissingCoreOutputs', ...
        'BLOCK 4 requires at least one existing BLOCK 1 core FREQ file.');
end
[analysisRows,design] = EmpaticMirroring_IndexAnalysisRows( ...
    dyadManifest,eligibleRows);

components = config.block4.components(:)';
meter = config.block4.metric_levels(:)';
ncomponents = numel(components);
nmeters = numel(meter);
nAnalysisRows = height(analysisRows);
nOutputs = nAnalysisRows*ncomponents;

manifestRow = repelem(eligibleRows,ncomponents,1);
component = repmat(components',nAnalysisRows,1);
phaseRQAFile = strings(nOutputs,1);
phaseRQAStatus = repmat("not processed",nOutputs,1);
phaseRQAErrorMessage = strings(nOutputs,1);

antialiasCutoff = config.block4.lp_cutoff_norm / ...
    config.block4.downsample_factor;
[b_butt,a_butt] = butter(config.block4.lp_order,antialiasCutoff,'low');
metricFields = {'RR','L','DET','ENTR','TT','LAM','Vmax','DIV'};

fprintf('\nBLOCK 4: processing %d recordings across %d components...\n', ...
    nAnalysisRows,ncomponents);

for componenti = 1:ncomponents
    which_comp = components(componenti);
    component_output_path = fullfile(config.block4.output_path, ...
        ['Component_' num2str(which_comp)]);
    if ~isfolder(component_output_path)
        mkdir(component_output_path);
    end

    PhaseRQA = phaseRQASettings(which_comp,config);
    phaseOutput = struct();
    for fieldi = 1:numel(metricFields)
        phaseOutput.(metricFields{fieldi}) = nan( ...
            design.nparticipants,design.nconds,nmeters,design.ntrials);
    end
    validTrialMask = false( ...
        design.nparticipants,design.nconds,design.ntrials);

    for analysisi = 1:nAnalysisRows
        rowIndex = eligibleRows(analysisi);
        longIndex = (analysisi-1)*ncomponents + componenti;
        input_file = coreFiles(rowIndex);
        output_file = phaseRQAOutputFile(input_file,component_output_path);
        phaseRQAFile(longIndex) = output_file;

        participanti = analysisRows.ParticipantIndex(analysisi);
        condi = analysisRows.ConditionIndex(analysisi);
        triali = analysisRows.RepetitionIndex(analysisi);

        try
            S = load(input_file,'FREQ','beat_frex');
            validateCoreInput(S,which_comp);
            analysis_info = phaseRQAAnalysisInfo(input_file, ...
                PhaseRQA,config,S.FREQ.srate);

            if isfile(output_file) && ~config.block4.overwrite_flag
                saved = load(output_file,'FREQrqa','PhaseRQA', ...
                    'analysis_info');
                validatePhaseRQAOutput(saved,analysis_info,nmeters);
                FREQrqa = saved.FREQrqa;
                phaseRQAStatus(longIndex) = "existing";
            else
                FREQ = preprocessTimeSeries(S.FREQ,which_comp,config, ...
                    b_butt,a_butt);
                FREQrqa = FREQNESS_PhaseSpaceRQA_Mocap( ...
                    FREQ,S.beat_frex, ...
                    'metric_levels',meter, ...
                    'component',which_comp, ...
                    'duration',config.block4.duration, ...
                    'standardize',config.block4.standardize, ...
                    'threshold_method',config.block4.threshold_method, ...
                    'threshold',config.block4.threshold, ...
                    'theiler_window',config.block4.theiler_window, ...
                    'lmin',config.block4.lmin, ...
                    'vmin',config.block4.vmin, ...
                    'store_matrices',config.block4.store_matrices, ...
                    'figure',config.block4.figure, ...
                    'animate',config.block4.animate, ...
                    'srate',FREQ.srate);
                validatePhaseRQAMetrics(FREQrqa,nmeters);
                if config.block4.save_flag
                    save(output_file,'FREQrqa','PhaseRQA', ...
                        'analysis_info','-v7.3');
                    phaseRQAStatus(longIndex) = "created";
                else
                    phaseRQAStatus(longIndex) = "computed";
                end
            end

            for metri = 1:nmeters
                for fieldi = 1:numel(metricFields)
                    field = metricFields{fieldi};
                    phaseOutput.(field)(participanti,condi,metri,triali) = ...
                        scalarMetric(FREQrqa(metri).(field),field);
                end
            end
            validTrialMask(participanti,condi,triali) = true;
        catch exception
            phaseRQAStatus(longIndex) = "error";
            phaseRQAErrorMessage(longIndex) = string(exception.message);
            warning('EmpaticMirroring:PhaseRQAAnalysisFailed', ...
                'BLOCK 4 failed for row %d, component %d: %s', ...
                rowIndex,which_comp,exception.message);
        end

        if mod(analysisi,25) == 0 || analysisi == nAnalysisRows
            fprintf('  component %d: processed %d/%d recordings\n', ...
                which_comp,analysisi,nAnalysisRows);
        end
    end

    PhaseRQA.output = phaseOutput;
    participantIds = design.participantIds;
    designTable = design.designTable;
    componentRows = analysisRows;
    componentRows.PhaseRQAIncluded = ...
        validTrialMask(sub2ind(size(validTrialMask), ...
        componentRows.ParticipantIndex,componentRows.ConditionIndex, ...
        componentRows.RepetitionIndex));
    phase_summary_file = fullfile(component_output_path, ...
        ['FREQNESS_PHASERQA_SUMMARY_Comp#' num2str(which_comp) '.mat']);
    if config.block4.save_flag
        save(phase_summary_file,'PhaseRQA','which_comp','meter', ...
            'participantIds','designTable','componentRows', ...
            'validTrialMask','-v7.3');
    end
end

phaseRQAManifest = table(manifestRow,component,phaseRQAFile, ...
    phaseRQAStatus,phaseRQAErrorMessage, ...
    'VariableNames',{'ManifestRow','Component','PhaseRQAFile', ...
    'PhaseRQAStatus','PhaseRQAErrorMessage'});
if ~isfolder(config.paths.qcOutputRoot)
    mkdir(config.paths.qcOutputRoot);
end
writetable(phaseRQAManifest,fullfile(config.paths.qcOutputRoot, ...
    'phase_rqa_analysis_manifest.csv'));

dyadManifest.PhaseRQAStatus = repmat( ...
    "not eligible",height(dyadManifest),1);
dyadManifest.PhaseRQAErrorMessage = strings(height(dyadManifest),1);
for analysisi = 1:nAnalysisRows
    rowIndex = eligibleRows(analysisi);
    rows = (analysisi-1)*ncomponents + (1:ncomponents);
    statuses = phaseRQAStatus(rows);
    if any(statuses == "error")
        dyadManifest.PhaseRQAStatus(rowIndex) = "error";
        messages = phaseRQAErrorMessage(rows);
        dyadManifest.PhaseRQAErrorMessage(rowIndex) = ...
            strjoin(messages(strlength(messages) > 0)," | ");
    elseif all(statuses == "created")
        dyadManifest.PhaseRQAStatus(rowIndex) = "created";
    elseif all(statuses == "existing")
        dyadManifest.PhaseRQAStatus(rowIndex) = "existing";
    elseif all(ismember(statuses,["created","existing","computed"]))
        dyadManifest.PhaseRQAStatus(rowIndex) = "available";
    end
end

available = ismember(phaseRQAStatus,["created","existing"]);
summary = struct( ...
    'eligibleCount',nOutputs, ...
    'createdCount',nnz(phaseRQAStatus == "created"), ...
    'existingCount',nnz(phaseRQAStatus == "existing"), ...
    'computedCount',nnz(phaseRQAStatus == "computed"), ...
    'errorCount',nnz(phaseRQAStatus == "error"), ...
    'availableCount',nnz(available), ...
    'phaseRQAManifest',phaseRQAManifest);

fprintf(['BLOCK 4 outputs available: %d (%d created, %d existing); ' ...
    '%d errors.\n'],summary.availableCount,summary.createdCount, ...
    summary.existingCount,summary.errorCount);

end


function validateBlock4Inputs(dyadManifest,config)

requiredManifest = {'DyadFile','Subject','TrialIndex','Instruction', ...
    'Complexity','Version','Movement'};
required = {'output_path','overwrite_flag','save_flag','components', ...
    'metric_levels','downsample_factor','lp_order','lp_cutoff_norm', ...
    'duration','standardize','threshold_method','threshold', ...
    'theiler_window','lmin','vmin','store_matrices','figure','animate', ...
    'max_dyads'};
if ~istable(dyadManifest) || ...
        ~all(ismember(requiredManifest,dyadManifest.Properties.VariableNames))
    error('EmpaticMirroring:PhaseRQAManifest', ...
        'dyadManifest is missing fields required for BLOCK 4.');
end
if ~isstruct(config) || ~isfield(config,'block4') || ...
        ~all(isfield(config.block4,required))
    error('EmpaticMirroring:PhaseRQAConfiguration', ...
        'The BLOCK 4 configuration is incomplete.');
end
logicalFields = {'overwrite_flag','save_flag','standardize', ...
    'store_matrices','figure','animate'};
for fieldi = 1:numel(logicalFields)
    value = config.block4.(logicalFields{fieldi});
    if ~islogical(value) || ~isscalar(value)
        error('EmpaticMirroring:PhaseRQAFlags', ...
            'config.block4.%s must be one logical value.', ...
            logicalFields{fieldi});
    end
end
positiveIntegerVector(config.block4.components,'components');
positiveIntegerScalar(config.block4.downsample_factor,'downsample_factor');
positiveIntegerScalar(config.block4.lp_order,'lp_order');
positiveIntegerScalar(config.block4.lmin,'lmin');
positiveIntegerScalar(config.block4.vmin,'vmin');
positiveIntegerOrInf(config.block4.max_dyads,'max_dyads');
if ~isnumeric(config.block4.metric_levels) || ...
        ~isreal(config.block4.metric_levels) || ...
        isempty(config.block4.metric_levels) || ...
        ~isvector(config.block4.metric_levels) || ...
        any(~isfinite(config.block4.metric_levels)) || ...
        any(config.block4.metric_levels <= 0)
    error('EmpaticMirroring:PhaseRQAMetricLevels', ...
        'metric_levels must be a positive finite vector.');
end
if ~isnumeric(config.block4.lp_cutoff_norm) || ...
        ~isscalar(config.block4.lp_cutoff_norm) || ...
        ~isfinite(config.block4.lp_cutoff_norm) || ...
        config.block4.lp_cutoff_norm <= 0 || ...
        config.block4.lp_cutoff_norm >= 1
    error('EmpaticMirroring:PhaseRQALowPass', ...
        'lp_cutoff_norm must lie strictly between zero and one.');
end
if ~isnumeric(config.block4.duration) || ...
        ~isreal(config.block4.duration) || ...
        numel(config.block4.duration) ~= 2 || ...
        any(~isfinite(config.block4.duration)) || ...
        config.block4.duration(1) < 0 || ...
        config.block4.duration(2) > 1 || ...
        config.block4.duration(1) >= config.block4.duration(2)
    error('EmpaticMirroring:PhaseRQADuration', ...
        'duration must be an increasing proportional interval within [0 1].');
end
if ~ismember(lower(string(config.block4.threshold_method)), ...
        ["max_fraction","fixed_rr"]) || ...
        ~isnumeric(config.block4.threshold) || ...
        ~isscalar(config.block4.threshold) || ...
        ~isfinite(config.block4.threshold) || ...
        config.block4.threshold <= 0 || config.block4.threshold >= 1
    error('EmpaticMirroring:PhaseRQAThreshold', ...
        'The phase-space RQA threshold configuration is invalid.');
end
if ~isnumeric(config.block4.theiler_window) || ...
        ~isscalar(config.block4.theiler_window) || ...
        ~isfinite(config.block4.theiler_window) || ...
        config.block4.theiler_window < 0 || ...
        config.block4.theiler_window ~= round(config.block4.theiler_window)
    error('EmpaticMirroring:PhaseRQATheiler', ...
        'theiler_window must be one non-negative integer.');
end

end


function positiveIntegerVector(value,name)

if ~isnumeric(value) || ~isreal(value) || isempty(value) || ...
        ~isvector(value) || any(~isfinite(value)) || ...
        any(value < 1) || any(value ~= round(value)) || ...
        numel(unique(value)) ~= numel(value)
    error('EmpaticMirroring:PhaseRQAPositiveIntegers', ...
        'config.block4.%s must contain unique positive integers.',name);
end

end


function positiveIntegerScalar(value,name)

if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || ...
        value < 1 || value ~= round(value)
    error('EmpaticMirroring:PhaseRQAPositiveInteger', ...
        'config.block4.%s must be one positive integer.',name);
end

end


function positiveIntegerOrInf(value,name)

if ~isnumeric(value) || ~isscalar(value) || ...
        ~(value == Inf || (isfinite(value) && value >= 1 && ...
        value == round(value)))
    error('EmpaticMirroring:PhaseRQAMaximum', ...
        'config.block4.%s must be a positive integer or Inf.',name);
end

end


function coreFiles = resolveCoreFiles(dyadManifest)

nRows = height(dyadManifest);
coreFiles = strings(nRows,1);
if ismember('CoreFile',dyadManifest.Properties.VariableNames)
    coreFiles = string(dyadManifest.CoreFile);
end
dyadFiles = string(dyadManifest.DyadFile);
for rowIndex = 1:nRows
    if strlength(coreFiles(rowIndex)) == 0 && ...
            strlength(dyadFiles(rowIndex)) > 0
        [inputFolder,inputStem] = fileparts(dyadFiles(rowIndex));
        coreFiles(rowIndex) = string(fullfile(inputFolder, ...
            "FREQNESS_CORE_" + inputStem + ".mat"));
    end
end

end


function settings = phaseRQASettings(which_comp,config)

settings = struct( ...
    'target_frex',[], ...
    'component',which_comp, ...
    'metric_levels',config.block4.metric_levels, ...
    'duration',config.block4.duration, ...
    'standardize',config.block4.standardize, ...
    'threshold_method',string(config.block4.threshold_method), ...
    'threshold',config.block4.threshold, ...
    'theiler_window',config.block4.theiler_window, ...
    'lmin',config.block4.lmin, ...
    'vmin',config.block4.vmin, ...
    'store_matrices',config.block4.store_matrices, ...
    'figure',config.block4.figure, ...
    'animate',config.block4.animate);

end


function validateCoreInput(S,which_comp)

if ~isfield(S,'FREQ') || ~isstruct(S.FREQ) || ...
        ~isfield(S,'beat_frex') || ...
        ~all(isfield(S.FREQ,{'ts','frex','srate'})) || ...
        ndims(S.FREQ.ts) ~= 4 || size(S.FREQ.ts,4) ~= 2 || ...
        size(S.FREQ.ts,1) < which_comp || ...
        ~isnumeric(S.beat_frex) || ...
        ~isequal(size(S.beat_frex),[1 2]) || ...
        any(~isfinite(S.beat_frex)) || any(S.beat_frex <= 0)
    error('EmpaticMirroring:PhaseRQACoreInput', ...
        'The BLOCK 1 FREQ output is incompatible with BLOCK 4.');
end

end


function FREQ = preprocessTimeSeries(FREQ,which_comp,config,b_butt,a_butt)

dwn = config.block4.downsample_factor;
if mod(FREQ.srate,dwn) ~= 0
    error('EmpaticMirroring:PhaseRQASampleRate', ...
        'FREQ.srate must be divisible by the BLOCK 4 downsample factor.');
end
nfrex = size(FREQ.ts,3);
nsubs = size(FREQ.ts,4);
filtered = zeros(ceil(size(FREQ.ts,2)/dwn),nfrex,nsubs, ...
    'like',FREQ.ts);
for subi = 1:nsubs
    for frexi = 1:nfrex
        ts = double(squeeze(FREQ.ts(which_comp,:,frexi,subi)));
        ts = filtfilt(b_butt,a_butt,ts);
        filtered(:,frexi,subi) = cast(ts(1:dwn:end),'like',FREQ.ts);
    end
end
FREQ.ts = FREQ.ts(:,1:dwn:end,:,:);
FREQ.ts(which_comp,:,:,:) = permute(filtered,[4 1 2 3]);
FREQ.srate = FREQ.srate/dwn;

end


function output_file = phaseRQAOutputFile(input_file,output_path)

[~,inputStem] = fileparts(input_file);
unitStem = erase(string(inputStem),"FREQNESS_CORE_");
output_file = string(fullfile(output_path, ...
    "FREQNESS_PHASERQA_" + unitStem + ".mat"));

end


function info = phaseRQAAnalysisInfo(input_file,PhaseRQA,config,inputSrate)

info = struct( ...
    'inputCoreFile',string(input_file), ...
    'PhaseRQA',PhaseRQA, ...
    'inputSrate',inputSrate, ...
    'downsample_factor',config.block4.downsample_factor, ...
    'outputSrate',inputSrate/config.block4.downsample_factor, ...
    'lp_order',config.block4.lp_order, ...
    'lp_cutoff_norm',config.block4.lp_cutoff_norm, ...
    'antialias_cutoff_normalized_to_input_nyquist', ...
    config.block4.lp_cutoff_norm/config.block4.downsample_factor);

end


function validatePhaseRQAOutput(saved,analysis_info,nmeters)

required = {'FREQrqa','PhaseRQA','analysis_info'};
if ~all(isfield(saved,required)) || ...
        ~isequaln(saved.analysis_info,analysis_info) || ...
        ~isequaln(saved.PhaseRQA,analysis_info.PhaseRQA)
    error('EmpaticMirroring:PhaseRQAOutputContract', ...
        'Existing BLOCK 4 output does not match the current configuration.');
end
validatePhaseRQAMetrics(saved.FREQrqa,nmeters);

end


function validatePhaseRQAMetrics(FREQrqa,nmeters)

fields = {'RR','L','DET','ENTR','TT','LAM','Vmax','DIV'};
if ~isstruct(FREQrqa) || numel(FREQrqa) ~= nmeters || ...
        ~all(isfield(FREQrqa,fields))
    error('EmpaticMirroring:PhaseRQAMetrics', ...
        'BLOCK 4 produced incomplete phase-space RQA metrics.');
end
for metri = 1:nmeters
    for fieldi = 1:numel(fields)
        scalarMetric(FREQrqa(metri).(fields{fieldi}),fields{fieldi});
    end
end

end


function value = scalarMetric(value,name)

if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value)
    error('EmpaticMirroring:PhaseRQAScalarMetric', ...
        'FREQrqa.%s must be one finite numeric value.',name);
end

end
