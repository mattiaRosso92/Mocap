function [dyadManifest,summary] = EmpaticMirroring_RunCoreAnalysis( ...
    dyadManifest,config,networkEstimatorContract)
%EMPATICMIRRORING_RUNCOREANALYSIS Run resumable FREQ-NESS dyad estimation.
%   Every saved artificial dyad is analyzed in [coordinates x time x 2]
%   format. Its synchronized bad_segments union is excluded from both
%   covariance matrices, and the FREQ output is saved beside the dyad.

if ~istable(dyadManifest) || ~all(ismember( ...
        {'DyadFile','DyadStatus'},dyadManifest.Properties.VariableNames))
    error('EmpaticMirroring:CoreManifest', ...
        'dyadManifest must contain DyadFile and DyadStatus columns.');
end
if nargin < 3 || ~istable(networkEstimatorContract) || ...
        ~ismember('ReadyForNetworkEstimation', ...
        networkEstimatorContract.Properties.VariableNames) || ...
        height(networkEstimatorContract) ~= 1 || ...
        ~networkEstimatorContract.ReadyForNetworkEstimation
    error('EmpaticMirroring:CoreEstimatorContract', ...
        ['Core analysis requires a MoCap estimator that applies ' ...
        'bad_segments to both covariance matrices.']);
end

validateCoreConfiguration(config);

nRows = height(dyadManifest);
coreFile = strings(nRows,1);
coreStatus = repmat("not eligible",nRows,1);
coreErrorMessage = strings(nRows,1);

dyadFiles = string(dyadManifest.DyadFile);
dyadStatuses = string(dyadManifest.DyadStatus);
eligibleRows = find(ismember(dyadStatuses,["created","existing"]) & ...
    strlength(dyadFiles) > 0 & isfile(dyadFiles));
if isfinite(config.block1.max_dyads)
    eligibleRows = eligibleRows(1:min( ...
        numel(eligibleRows),config.block1.max_dyads));
end

fprintf('\nRunning core FREQ-NESS analysis for %d artificial dyads...\n', ...
    numel(eligibleRows));

for eligibleIndex = 1:numel(eligibleRows)
    rowIndex = eligibleRows(eligibleIndex);
    inputFile = dyadFiles(rowIndex);
    outputFile = coreOutputFile(inputFile);
    coreFile(rowIndex) = outputFile;

    try
        reuseExisting = false;
        if isfile(outputFile) && ~config.block1.overwrite_flag
            savedCore = load(outputFile,'FREQ');
            try
                validateCoreOutput(savedCore.FREQ,[],config);
                reuseExisting = true;
            catch staleException
                warning('EmpaticMirroring:StaleCoreCache', ...
                    ['Regenerating %s because the existing FREQ output ' ...
                     'predates the marker policy: %s'],outputFile, ...
                    staleException.message);
            end
        end
        if reuseExisting
            coreStatus(rowIndex) = "existing";
        else
            savedDyad = load(inputFile,'markData','srate', ...
                'bad_segments','bad_segments_by_participant', ...
                'marker_reference','marker_policy', ...
                'dyad_info');
            validateDyadInput(savedDyad,config);

            markData = savedDyad.markData;
            srate = savedDyad.srate;
            beat_frex = config.block1.beat_frex;
            frex = config.block1.frex;

            % Compute FREQ-NESS with GED, following the DyadicDance block.
            FREQ = FREQNESS_NetworkEstimation_Mocap( ...
                markData,frex,srate, ...
                'duration',config.block1.duration, ...
                'fwidth',config.block1.fwidth, ...
                'filter',config.block1.filter, ...
                'regularisation',config.block1.regularisation, ...
                'ncomps',config.block1.ncomps, ...
                'bad_segments',savedDyad.bad_segments);
            % Retain both the synchronized estimator exclusion and the
            % role-specific provenance used by downstream analyses.
            FREQ.bad_segments_by_participant = ...
                savedDyad.bad_segments_by_participant;
            FREQ.gap_info.bad_segments_by_participant = ...
                savedDyad.bad_segments_by_participant;
            assert(size(FREQ.evals,1) == size(markData,1), ...
                'NetworkEstimation did not retain the complete eigenspectrum.');
            assert(size(FREQ.evecs,2) == config.block1.ncomps, ...
                'NetworkEstimation retained an unexpected component count.');
            FREQ.frex_norm = FREQ.frex ./ beat_frex;
            validateCoreOutput(FREQ,savedDyad,config);

            analysis_info = buildAnalysisInfo(inputFile,frex,beat_frex, ...
                config,savedDyad.bad_segments);
            marker_reference = savedDyad.marker_reference;
            dyad_info = savedDyad.dyad_info;
            if config.block1.save_flag
                save(outputFile,'FREQ','beat_frex','analysis_info', ...
                    'marker_reference','dyad_info','srate','-v7.3');
                coreStatus(rowIndex) = "created";
            else
                coreStatus(rowIndex) = "computed";
            end
        end
    catch exception
        coreStatus(rowIndex) = "error";
        coreErrorMessage(rowIndex) = string(exception.message);
        warning('EmpaticMirroring:CoreAnalysisFailed', ...
            'Core analysis failed for row %d: %s', ...
            rowIndex,exception.message);
    end

    if mod(eligibleIndex,25) == 0 || eligibleIndex == numel(eligibleRows)
        fprintf('  processed %d/%d core analyses\n', ...
            eligibleIndex,numel(eligibleRows));
    end
end

dyadManifest.CoreFile = coreFile;
dyadManifest.CoreStatus = coreStatus;
dyadManifest.CoreErrorMessage = coreErrorMessage;
if ~isfolder(config.paths.qcOutputRoot)
    mkdir(config.paths.qcOutputRoot);
end
writetable(dyadManifest,fullfile(config.paths.qcOutputRoot, ...
    'core_analysis_manifest.csv'));

available = coreStatus == "created" | coreStatus == "existing";
summary = struct( ...
    'eligibleCount',numel(eligibleRows), ...
    'createdCount',nnz(coreStatus == "created"), ...
    'existingCount',nnz(coreStatus == "existing"), ...
    'computedCount',nnz(coreStatus == "computed"), ...
    'errorCount',nnz(coreStatus == "error"), ...
    'availableCount',nnz(available));

fprintf(['Core FREQ-NESS outputs available: %d (%d created, %d existing); ' ...
    '%d errors.\n'],summary.availableCount,summary.createdCount, ...
    summary.existingCount,summary.errorCount);

end


function validateCoreConfiguration(config)

requiredBlockFields = {'beat_frex','frex','duration','fwidth', ...
    'filter','regularisation','ncomps','overwrite_flag','save_flag', ...
    'max_dyads'};
if ~isstruct(config) || ~isfield(config,'block1') || ...
        ~all(isfield(config.block1,requiredBlockFields))
    error('EmpaticMirroring:CoreConfiguration', ...
        'The core network configuration is incomplete.');
end
frex = config.block1.frex;
beat_frex = config.block1.beat_frex;
if ~isnumeric(frex) || ~isreal(frex) || isempty(frex) || ...
        ~ismatrix(frex) || any(~isfinite(frex(:))) || ...
        any(frex(:) <= 0) || ...
        ~(isvector(frex) || size(frex,2) == 2)
    error('EmpaticMirroring:CoreFrequenciesRequired', ...
        ['Declare config.block1.frex as a positive shared frequency ' ...
        'vector or an [nFrex x 2] dyad matrix.']);
end
if ~isnumeric(beat_frex) || ~isreal(beat_frex) || ...
        ~isequal(size(beat_frex),[1 2]) || ...
        any(~isfinite(beat_frex)) || any(beat_frex <= 0)
    error('EmpaticMirroring:CoreBeatFrequencies', ...
        'config.block1.beat_frex must contain one positive value per dyad member.');
end
if ~islogical(config.block1.overwrite_flag) || ...
        ~isscalar(config.block1.overwrite_flag) || ...
        ~islogical(config.block1.save_flag) || ...
        ~isscalar(config.block1.save_flag)
    error('EmpaticMirroring:CoreFlags', ...
        'Core overwrite and save settings must be scalar logical values.');
end
if ~isnumeric(config.block1.max_dyads) || ...
        ~isscalar(config.block1.max_dyads) || ...
        ~(config.block1.max_dyads == Inf || ...
        (isfinite(config.block1.max_dyads) && ...
        config.block1.max_dyads >= 1 && ...
        config.block1.max_dyads == round(config.block1.max_dyads)))
    error('EmpaticMirroring:CoreMaximum', ...
        'config.block1.max_dyads must be a positive integer or Inf.');
end

end


function validateDyadInput(savedDyad,config)

required = {'markData','srate','bad_segments', ...
    'bad_segments_by_participant', ...
    'marker_reference','marker_policy','dyad_info'};
if ~all(isfield(savedDyad,required))
    error('EmpaticMirroring:CoreDyadFields', ...
        'Artificial dyad lacks fields required for core analysis.');
end
expectedSamples = round(config.block1.duration*savedDyad.srate);
if ~isnumeric(savedDyad.markData) || ndims(savedDyad.markData) ~= 3 || ...
        size(savedDyad.markData,2) < expectedSamples || ...
        size(savedDyad.markData,3) ~= 2
    error('EmpaticMirroring:CoreDyadShape', ...
        ['markData must contain the requested duration in ' ...
        '[coordinates x time x 2 participants] format.']);
end
if any(~isfinite(savedDyad.markData),'all')
    error('EmpaticMirroring:CoreUnexpectedMissingData', ...
        ['Artificial dyad contains unresolved missing data; its source ' ...
         'recording should have been excluded by marker-policy QC.']);
end
if size(savedDyad.markData,1) ~= 3*config.markers.expectedCount || ...
        ~isstruct(savedDyad.marker_policy) || ...
        ~isfield(savedDyad.marker_policy,'version') || ...
        string(savedDyad.marker_policy.version) ~= ...
        string(config.markers.policyVersion)
    error('EmpaticMirroring:CoreDyadMarkerPolicy', ...
        'Artificial dyad does not match the configured marker policy.');
end

end


function validateCoreOutput(FREQ,savedDyad,config)

required = {'evals','evecs','pats','ts','frex','frex_norm','fwhm', ...
    'srate','duration','bad_segments','bad_segments_by_participant', ...
    'gap_info','regularisation'};
if ~isstruct(FREQ) || ~all(isfield(FREQ,required))
    error('EmpaticMirroring:CoreOutputFields', ...
        'Saved FREQ output is incomplete or predates the current contract.');
end
nfrex = size(config.block1.frex,1);
if isvector(config.block1.frex)
    nfrex = numel(config.block1.frex);
end
if size(FREQ.evals,1) ~= 3*config.markers.expectedCount || ...
        size(FREQ.evals,2) ~= nfrex || ...
        size(FREQ.evecs,2) ~= config.block1.ncomps || ...
        size(FREQ.evecs,3) ~= nfrex || size(FREQ.evecs,4) ~= 2 || ...
        size(FREQ.pats,4) ~= 2 || size(FREQ.ts,4) ~= 2 || ...
        FREQ.duration ~= config.block1.duration || ...
        FREQ.regularisation ~= config.block1.regularisation || ...
        FREQ.srate ~= config.sampling.outputHz || ...
        ~isequal(FREQ.frex,config.block1.frex) || ...
        ~isequal(FREQ.frex_norm,FREQ.frex./config.block1.beat_frex)
    error('EmpaticMirroring:CoreOutputShape', ...
        'FREQ output does not match the configured core-analysis contract.');
end
if ~isempty(savedDyad) && ...
        (size(FREQ.evals,1) ~= size(savedDyad.markData,1) || ...
        FREQ.srate ~= savedDyad.srate || ...
        ~isequal(FREQ.bad_segments,savedDyad.bad_segments))
    error('EmpaticMirroring:CoreOutputProvenance', ...
        'FREQ output does not match its artificial-dyad input.');
end

end


function outputFile = coreOutputFile(inputFile)

[inputFolder,inputStem] = fileparts(inputFile);
outputFile = string(fullfile(inputFolder, ...
    "FREQNESS_CORE_" + inputStem + ".mat"));

end


function info = buildAnalysisInfo(inputFile,frex,beat_frex,config,badSegments)

info = struct( ...
    'inputDyadFile',string(inputFile), ...
    'frex',frex, ...
    'beat_frex',beat_frex, ...
    'duration',config.block1.duration, ...
    'fwidth',config.block1.fwidth, ...
    'filter',string(config.block1.filter), ...
    'regularisation',config.block1.regularisation, ...
    'ncomps',config.block1.ncomps, ...
    'badSegments',badSegments, ...
    'badSegmentsPolicy', ...
    ['Synchronized dyad union excluded from both narrowband and ' ...
    'broadband covariance matrices.']);

end
