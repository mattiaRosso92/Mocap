%% Empatic mirroring: excluded-recording sensitivity analysis
% This workflow never changes primary outputs. It waives only the three
% documented participant-folder annotations, reapplies every objective QC
% rule, computes newly admitted recordings, and combines compact results
% with the retained cohort for a like-for-like sensitivity analysis.

clearvars
close all
clc

studyRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(studyRoot,'functions'));

primaryConfig = EmpaticMirroring_Config();
[recoveredConfig,combinedConfig] = ...
    EmpaticMirroring_ConfigureRecoverySensitivity(primaryConfig);

assert(isfolder(primaryConfig.paths.dataRoot), ...
    'Data directory not found: %s',primaryConfig.paths.dataRoot);
assert(isfolder(primaryConfig.paths.toolboxRoot), ...
    'FREQ-NESS MoCap toolbox not found: %s', ...
    primaryConfig.paths.toolboxRoot);
addpath(primaryConfig.paths.toolboxRoot);
addpath(fullfile(primaryConfig.paths.toolboxRoot,'FREQNESS_Functions'));
addpath(fullfile(primaryConfig.paths.toolboxRoot, ...
    'FREQNESS_ExternalFunctions'));

fprintf('\n============================================================\n');
fprintf('EXCLUDED-RECORDING SENSITIVITY WORKFLOW\n');
fprintf('Primary outputs (read only): %s\n', ...
    primaryConfig.paths.outputRoot);
fprintf('Sensitivity outputs: %s\n', ...
    primaryConfig.sensitivity.output_root);
fprintf(['Policy: waive participant-folder annotations only; retain all ' ...
    'objective QC and bad-sample exclusions.\n']);
fprintf('============================================================\n');

%% SENSITIVITY 1 - REAPPLY OBJECTIVE QC

primaryQCFile = fullfile(primaryConfig.paths.qcOutputRoot, ...
    'frame_count_qc.csv');
if primaryConfig.sensitivity.refresh_qc || ~isfile(primaryQCFile)
    fprintf('\nSENSITIVITY 1: refreshing full raw-data QC.\n');
    frameQC = EmpaticMirroring_FrameCountQC(recoveredConfig);
    qcSource = "fresh raw-data scan";
else
    fprintf('\nSENSITIVITY 1: reusing the primary QC audit (no raw rescan).\n');
    frameQC = readtable(primaryQCFile,'TextType','string');
    qcSource = string(primaryQCFile);
end
[sensitivityQC,recoveryAudit,recoverySummary] = ...
    EmpaticMirroring_BuildRecoverySensitivityQC( ...
    frameQC,recoveredConfig);
fprintf('QC source: %s\n',qcSource);

if ~primaryConfig.sensitivity.run
    fprintf(['\nSensitivity execution is disabled. The recovery audit is ' ...
        'complete; set config.sensitivity.run = true to execute the ' ...
        'resume-aware analysis stages below.\n']);
    return
end

%% SENSITIVITY 2 - COMPUTE RECOVERED RECORDINGS ONLY

networkEstimatorContract = ...
    EmpaticMirroring_CheckNetworkEstimatorContract(recoveredConfig);
assert(networkEstimatorContract.ReadyForNetworkEstimation, ...
    'The active MoCap estimator is incompatible with bad_segments.');

recoveredCoreManifestFile = fullfile( ...
    recoveredConfig.paths.qcOutputRoot,'recovered_core_manifest.csv');
if primaryConfig.sensitivity.run_recovery_core
    fprintf('\nSENSITIVITY 2A: materializing recovered artificial dyads.\n');
    recoveredManifest = EmpaticMirroring_BuildDyadManifest( ...
        sensitivityQC,recoveredConfig);
    [recoveredManifest,dyadSummary] = ...
        EmpaticMirroring_CreateArtificialDyads( ...
        recoveredManifest,recoveredConfig,sensitivityQC);
    assert(dyadSummary.errorCount == 0 && ...
        dyadSummary.availableCount == recoverySummary.recoveredCount, ...
        'Recovered dyad generation was incomplete.');

    fprintf('\nSENSITIVITY 2B: running core FREQ-NESS for recovered rows.\n');
    [recoveredManifest,coreSummary] = ...
        EmpaticMirroring_RunCoreAnalysis(recoveredManifest, ...
        recoveredConfig,networkEstimatorContract);
    assert(coreSummary.errorCount == 0 && ...
        coreSummary.availableCount == recoverySummary.recoveredCount, ...
        'Recovered core analysis was incomplete.');
    writetable(recoveredManifest,recoveredCoreManifestFile);
elseif isfile(recoveredCoreManifestFile)
    fprintf('\nSENSITIVITY 2: reusing recovered core manifest.\n');
    recoveredManifest = readtable(recoveredCoreManifestFile, ...
        'TextType','string');
else
    error('EmpaticMirroring:SensitivityMissingRecoveredCore', ...
        ['Recovered core execution is disabled and no recovered core ' ...
         'manifest exists.']);
end

recoveredLandscapeManifestFile = fullfile( ...
    recoveredConfig.paths.qcOutputRoot, ...
    'recovered_landscape_manifest.csv');
if primaryConfig.sensitivity.run_recovered_blocks
    fprintf(['\nSENSITIVITY 2C: running BLOCKS 2-3 for recovered rows ' ...
        'only.\n']);
    [recoveredManifest,landscapeSummary] = ...
        EmpaticMirroring_RunLandscapeAnalysis( ...
        recoveredManifest,recoveredConfig);
    [recoveredManifest,phaseRQASummary] = ...
        EmpaticMirroring_RunPhaseSpaceRQA( ...
        recoveredManifest,recoveredConfig);
    [recoveredManifest,coordinationSummary] = ...
        EmpaticMirroring_RunCoordinationAnalysis( ...
        recoveredManifest,recoveredConfig);
    assert(landscapeSummary.errorCount == 0 && ...
        coordinationSummary.errorCount == 0 && ...
        phaseRQASummary.errorCount == 0, ...
        'At least one recovered downstream analysis failed.');
    EmpaticMirroring_ExportStatistics(recoveredConfig);
    writetable(recoveredManifest,recoveredLandscapeManifestFile);
elseif isfile(recoveredLandscapeManifestFile)
    fprintf('\nSENSITIVITY 2C: reusing recovered BLOCK 2-4 outputs.\n');
    recoveredManifest = readtable(recoveredLandscapeManifestFile, ...
        'TextType','string');
else
    error('EmpaticMirroring:SensitivityMissingRecoveredBlocks', ...
        ['Recovered downstream execution is disabled and no recovered ' ...
         'landscape manifest exists.']);
end

%% SENSITIVITY 3 - COMBINE WITHOUT RECOMPUTING PRIMARY RECORDINGS

if primaryConfig.sensitivity.build_combined_outputs
    fprintf(['\nSENSITIVITY 3: combining existing primary outputs with ' ...
        'recovered-only outputs.\n']);
    primaryCore = readRequiredTable(fullfile( ...
        primaryConfig.paths.qcOutputRoot,'core_analysis_manifest.csv'));
    primaryLandscape = readRequiredTable(fullfile( ...
        primaryConfig.paths.qcOutputRoot, ...
        'landscape_analysis_manifest.csv'));
    [combinedCoreManifest,combinedCoreSummary] = ...
        EmpaticMirroring_CombineSensitivityManifests( ...
        primaryCore,recoveredManifest,"CoreStatus","CoreFile", ...
        fullfile(combinedConfig.paths.qcOutputRoot, ...
        'combined_core_manifest.csv'));
    [combinedManifest,combinedLandscapeSummary] = ...
        EmpaticMirroring_CombineSensitivityManifests( ...
        primaryLandscape,recoveredManifest,"LandscapeStatus", ...
        "LandscapeFile",fullfile(combinedConfig.paths.qcOutputRoot, ...
        'combined_landscape_manifest.csv'));
    assert(combinedCoreSummary.combinedCount == ...
        combinedLandscapeSummary.combinedCount, ...
        'Combined core and landscape recording counts differ.');

    mergeSummary = EmpaticMirroring_MergeSensitivitySummaries( ...
        primaryConfig,recoveredConfig,combinedConfig);
    groupSummary = EmpaticMirroring_RunGroupAnalysis( ...
        combinedManifest,combinedConfig);
    statisticsSummary = EmpaticMirroring_ExportStatistics(combinedConfig);
    fprintf(['Combined cohort: %d recordings, %d participants, %d ' ...
        'statistical rows.\n'],combinedLandscapeSummary.combinedCount, ...
        combinedLandscapeSummary.participantCount, ...
        statisticsSummary.rowCount);
else
    error('EmpaticMirroring:SensitivityCombinedOutputsDisabled', ...
        'Combined sensitivity outputs must exist before modelling.');
end

%% SENSITIVITY 4 - IDENTICAL STATISTICS AND PRIMARY COMPARISON

sensitivityStatsRoot = fullfile(combinedConfig.paths.outputRoot, ...
    '06_Statistics_Results');
if primaryConfig.sensitivity.run_statistics
    fprintf('\nSENSITIVITY 4A: fitting the unchanged primary R models.\n');
    runRScript(fullfile(studyRoot,'EmpaticMirroring_Stats.R'), ...
        ["--input=" + statisticsSummary.combinedCsvFile, ...
        "--similarity-input=" + ...
        statisticsSummary.landscapeSimilarityCsvFile, ...
        "--output=" + string(sensitivityStatsRoot)], ...
        primaryConfig.sensitivity.overwrite, ...
        fullfile(sensitivityStatsRoot,'All_Full_Model_ANOVAs_BH.csv'));
end

comparisonRoot = fullfile(primaryConfig.sensitivity.output_root, ...
    'Comparison');
if primaryConfig.sensitivity.compare_results
    fprintf('\nSENSITIVITY 4B: comparing primary and sensitivity results.\n');
    runRScript(fullfile(studyRoot, ...
        'EmpaticMirroring_CompareSensitivity.R'),[ ...
        "--primary-input=" + fullfile( ...
        primaryConfig.block5.output_path,'OUT2R_AllComponents.csv'), ...
        "--sensitivity-input=" + statisticsSummary.combinedCsvFile, ...
        "--primary-results=" + fullfile( ...
        primaryConfig.paths.outputRoot,'06_Statistics_Results'), ...
        "--sensitivity-results=" + string(sensitivityStatsRoot), ...
        "--output=" + string(comparisonRoot)], ...
        primaryConfig.sensitivity.overwrite, ...
        fullfile(comparisonRoot,'Sensitivity_Change_Summary.csv'));
end

fprintf('\n============================================================\n');
fprintf('SENSITIVITY WORKFLOW COMPLETE\n');
fprintf('Recovered recordings: %d/%d candidates\n', ...
    recoverySummary.recoveredCount,recoverySummary.candidateCount);
fprintf('Combined outputs: %s\n',combinedConfig.paths.outputRoot);
fprintf('Comparison outputs: %s\n',comparisonRoot);
fprintf(['Interpretation rule: conclusions are robust only when effect ' ...
    'direction and inferential status remain substantively stable.\n']);
fprintf('============================================================\n');


function tableOutput = readRequiredTable(file)

assert(isfile(file),'Required primary output is missing: %s',file);
tableOutput = readtable(file,'TextType','string');

end


function runRScript(scriptFile,arguments,overwrite,sentinelFile)

if isfile(sentinelFile) && ~overwrite
    fprintf('  reusing existing R outputs: %s\n',sentinelFile);
    return
end
commandParts = ["Rscript",quoteArgument(scriptFile), ...
    arrayfun(@quoteArgument,arguments)];
if overwrite
    commandParts(end+1) = "--overwrite";
end
command = strjoin(commandParts," ");
[status,output] = system(command);
fprintf('%s',output);
if status ~= 0
    error('EmpaticMirroring:SensitivityRFailure', ...
        'R workflow failed with status %d.',status);
end

end


function output = quoteArgument(input)

quotationMark = string(char(34));
output = quotationMark + string(input) + quotationMark;

end
