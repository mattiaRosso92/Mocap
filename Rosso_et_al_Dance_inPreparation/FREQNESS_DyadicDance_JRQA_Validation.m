%% BLOCK 0 - SETTINGS, STARTUP, AND NON-OVERWRITING OUTPUT ROUTING

% This validation workflow reads the completed core FREQ-NESS estimates and
% writes only to 03_Coordination_JRQA_Validated and its dedicated statistics
% folders. Historical JRQA, phase-space RQA, and core outputs are read-only.
script_file = mfilename('fullpath');
path_script = fileparts(script_file);
path_repo = fileparts(path_script);
path_data = fullfile(path_repo,'Dance_Data');
results_path = fullfile( ...
    path_data,'FREQNESS_Results_Rosso_et_al_inPreparation');

CFG = struct();
CFG.core_path = fullfile(results_path,'01_Core');
CFG.output_path = fullfile( ...
    results_path,'03_Coordination_JRQA_Validated');
CFG.statistics_path = fullfile( ...
    results_path,'06_Statistics_R','JRQA_Validated');
CFG.overwrite_flag = false;
CFG.components = 1:2;
CFG.metric_levels = [0.25 0.5 1 2];
CFG.duration = [0.15 0.85];
CFG.original_srate = 250;
CFG.target_srate = 25;
CFG.lowpass_cutoff = 10;
CFG.filter_order = 4;
CFG.standardize = true;
% Normalization is performed inside the toolbox, after filtering and cropping.
CFG.primary_specification = 'FixedDyadRadius';
CFG.maximum_lag = 20;
CFG.maximum_dimension = 5;
CFG.fnn_threshold = 0.10;
CFG.radius_fraction = 0.10;
CFG.robust_marginal_rr = 0.05;
CFG.lmin = 2;
CFG.vmin = 2;
CFG.surrogate_flag = true;
CFG.surrogate_dyads = [1 9 18 26 35];
CFG.surrogate_conditions = 1:4;
CFG.surrogate_trials = 1;
CFG.n_surrogates = 100;
CFG.surrogate_random_seed = 1729;

CFG.ndyads = 35;
CFG.list_dyads = [1:12 14:31 33:CFG.ndyads];
CFG.nconds = 4;
CFG.ntrials = 8;
CFG.nsubs = 2;

assert(isfolder(CFG.core_path), ...
    'Completed core output folder not found: %s',CFG.core_path);
assert(~strcmp(CFG.output_path,fullfile(results_path,'03_Coordination')), ...
    'Validated JRQA must not use the historical coordination folder.');
if ~isfolder(CFG.output_path)
    mkdir(CFG.output_path)
end
if ~isfolder(CFG.statistics_path)
    mkdir(CFG.statistics_path)
end

path_toolbox = fullfile(path_repo,'FREQNESS_Mocap_Toolbox');
addpath(path_toolbox)
FREQNESS_Startup_Mocap();

configuration_file = fullfile( ...
    CFG.output_path,'FREQNESS_JRQA_Validation_Configuration.mat');
if ~isfile(configuration_file) || CFG.overwrite_flag
    save(configuration_file,'CFG')
end


%% BLOCK 1 - COMPONENT-SPECIFIC EMBEDDING PARAMETER ESTIMATION

nmeters = numel(CFG.metric_levels);
for componenti = 1:numel(CFG.components)

    which_comp = CFG.components(componenti);
    component_parameter_path = fullfile( ...
        CFG.output_path,'ParameterEstimation', ...
        ['Component_' num2str(which_comp)]);
    if ~isfolder(component_parameter_path)
        mkdir(component_parameter_path)
    end
    parameter_file = fullfile(component_parameter_path, ...
        ['JRQA_ParameterEstimates_Comp#' num2str(which_comp) '.mat']);

    if isfile(parameter_file) && ~CFG.overwrite_flag
        loaded_parameters = load(parameter_file,'ParameterEstimates');
        ParameterEstimates = loaded_parameters.ParameterEstimates;
        parameter_update_flag = false;
    else
        parameter_size = [CFG.nsubs CFG.ndyads CFG.nconds ...
            nmeters CFG.ntrials];
        ParameterEstimates = struct( ...
            'tau',nan(parameter_size), ...
            'm',nan(parameter_size), ...
            'ps',nan(parameter_size), ...
            'tau_fallback',false(parameter_size), ...
            'm_fallback',false(parameter_size), ...
            'selected_frequencies',nan(parameter_size), ...
            'component',which_comp, ...
            'complete',false, ...
            'version','validated-v1');
        parameter_update_flag = true;
    end

    for condi = 1:CFG.nconds
        condition_update_flag = false;
        for dyadi = CFG.list_dyads
            fprintf(['Parameter estimation: Component %d, Condition %d, ' ...
                'Dyad %d\n'],which_comp,condi,dyadi);
            for triali = 1:CFG.ntrials
                existing_tau = ParameterEstimates.tau( ...
                    :,dyadi,condi,:,triali);
                if all(isfinite(existing_tau),'all') && ...
                        ~CFG.overwrite_flag
                    continue
                end

                input_file = fullfile(CFG.core_path,sprintf( ...
                    'FREQNESS_CORE_D%d_C%d_T%d.mat', ...
                    dyadi,condi,triali));
                assert(isfile(input_file),'Missing core output: %s',input_file);
                S = load(input_file,'GED','beat_frex');

                this_parameters = FREQNESS_JRQAParameters_Mocap( ...
                    S.GED,S.beat_frex,CFG.original_srate, ...
                    'metric_levels',CFG.metric_levels, ...
                    'component',which_comp, ...
                    'duration',CFG.duration, ...
                    'target_srate',CFG.target_srate, ...
                    'lowpass_cutoff',CFG.lowpass_cutoff, ...
                    'filter_order',CFG.filter_order, ...
                    'standardize',CFG.standardize, ...
                    'maximum_lag',CFG.maximum_lag, ...
                    'maximum_dimension',CFG.maximum_dimension, ...
                    'fnn_threshold',CFG.fnn_threshold, ...
                    'radius_fraction',CFG.radius_fraction);

                destination = [CFG.nsubs 1 1 nmeters 1];
                ParameterEstimates.tau(:,dyadi,condi,:,triali) = ...
                    reshape(this_parameters.tau,destination);
                ParameterEstimates.m(:,dyadi,condi,:,triali) = ...
                    reshape(this_parameters.m,destination);
                ParameterEstimates.ps(:,dyadi,condi,:,triali) = ...
                    reshape(this_parameters.ps,destination);
                ParameterEstimates.tau_fallback( ...
                    :,dyadi,condi,:,triali) = reshape( ...
                    this_parameters.TauFallback,destination);
                ParameterEstimates.m_fallback( ...
                    :,dyadi,condi,:,triali) = reshape( ...
                    this_parameters.DimensionFallback,destination);
                ParameterEstimates.selected_frequencies( ...
                    :,dyadi,condi,:,triali) = reshape( ...
                    this_parameters.SelectedFrequencies,destination);
                parameter_update_flag = true;
                condition_update_flag = true;
            end
        end

        % A condition-level checkpoint makes this expensive stage resumable.
        if condition_update_flag
            save(parameter_file,'ParameterEstimates','CFG','-v7.3')
        end
    end

    ParameterEstimates.complete = all(isfinite( ...
        ParameterEstimates.tau(:,CFG.list_dyads,:,:,:)),'all') && ...
        all(isfinite(ParameterEstimates.m( ...
        :,CFG.list_dyads,:,:,:)),'all') && ...
        all(isfinite(ParameterEstimates.ps( ...
        :,CFG.list_dyads,:,:,:)),'all');
    assert(ParameterEstimates.complete, ...
        'Parameter estimation is incomplete for Component %d.',which_comp);
    if parameter_update_flag || ~isfile(parameter_file)
        save(parameter_file,'ParameterEstimates','CFG','-v7.3')
    end


    %% BLOCK 2 - FIXED COMPONENT-LEVEL PARAMETER SPECIFICATIONS

    valid_tau = ParameterEstimates.tau(:,CFG.list_dyads,:,:,:);
    valid_m = ParameterEstimates.m(:,CFG.list_dyads,:,:,:);
    valid_ps = ParameterEstimates.ps(:,CFG.list_dyads,:,:,:);

    ManuscriptJRQA = struct();
    ManuscriptJRQA.tau = round(mean(valid_tau,'all','omitnan'));
    ManuscriptJRQA.m = round(mean(valid_m,'all','omitnan'));
    ManuscriptJRQA.ps = round(mean(valid_ps,'all','omitnan'),1);
    ManuscriptJRQA.Aggregation = 'mean_then_round';
    ManuscriptJRQA.ThresholdMethod = 'radius';
    ManuscriptJRQA.TheilerWindow = 0;
    ManuscriptJRQA.Component = which_comp;
    ManuscriptJRQA.Version = 'validated-v1-manuscript';

    RobustJRQA = struct();
    RobustJRQA.tau = round(median(valid_tau,'all','omitnan'));
    RobustJRQA.m = ceil(median(valid_m,'all','omitnan'));
    RobustJRQA.ps = [];
    RobustJRQA.Aggregation = 'median_tau_and_upward_rounded_median_m';
    RobustJRQA.ThresholdMethod = 'fixed_rr';
    RobustJRQA.TargetMarginalRR = CFG.robust_marginal_rr;
    RobustJRQA.TheilerWindow = ...
        (RobustJRQA.m-1)*RobustJRQA.tau;
    RobustJRQA.Component = which_comp;
    RobustJRQA.Version = 'validated-v1-robustness';

    FaithfulAdaptiveMaxJRQA = struct();
    FaithfulAdaptiveMaxJRQA.tau = ManuscriptJRQA.tau;
    FaithfulAdaptiveMaxJRQA.m = ManuscriptJRQA.m;
    FaithfulAdaptiveMaxJRQA.ps = [];
    FaithfulAdaptiveMaxJRQA.RadiusFraction = CFG.radius_fraction;
    FaithfulAdaptiveMaxJRQA.Aggregation = ...
        'manuscript_group_embedding_with_trial_adaptive_radius';
    FaithfulAdaptiveMaxJRQA.ThresholdMethod = 'adaptive_max_radius';
    FaithfulAdaptiveMaxJRQA.TheilerWindow = 0;
    FaithfulAdaptiveMaxJRQA.Component = which_comp;
    FaithfulAdaptiveMaxJRQA.Version = 'validated-v2-faithful-adaptive-max';

    parameter_summary_file = fullfile(component_parameter_path, ...
        ['JRQA_ParameterSummary_Comp#' num2str(which_comp) '.mat']);
    if ~isfile(parameter_summary_file) || CFG.overwrite_flag
        save(parameter_summary_file,'ManuscriptJRQA','RobustJRQA', ...
            'ParameterEstimates','CFG','-v7.3')
    end


    %% BLOCK 3 - VALIDATED JRQA SPECIFICATIONS

    specifications = struct( ...
        'name',{'CorrectedManuscript','Robustness', ...
        'FaithfulAdaptiveMax','FixedDyadRadius'}, ...
        'JRQA',{ManuscriptJRQA,RobustJRQA,FaithfulAdaptiveMaxJRQA, ...
        FaithfulAdaptiveMaxJRQA}, ...
        'threshold_method',{'radius','fixed_rr','adaptive_max_radius','radius'}, ...
        'threshold',{[],CFG.robust_marginal_rr,CFG.radius_fraction,[]}, ...
        'theiler_window',{0,RobustJRQA.TheilerWindow,0,0});

    for specificationi = 1:numel(specifications)
        specification = specifications(specificationi);
        component_output_path = fullfile( ...
            CFG.output_path,specification.name, ...
            ['Component_' num2str(which_comp)]);
        if ~isfolder(component_output_path)
            mkdir(component_output_path)
        end
        summary_file = fullfile(component_output_path, ...
            ['FREQNESS_JRQA_VALIDATED_SUMMARY_Comp#' ...
            num2str(which_comp) '.mat']);
        if isfile(summary_file) && ~CFG.overwrite_flag
            fprintf(['%s JRQA: Component %d summary already exists; ' ...
                'skipping completed specification.\n'], ...
                specification.name,which_comp);
            continue
        end

        if strcmp(specification.name,'FixedDyadRadius')
            % Pool all conditions, trials and metric levels with equal weight.
            % Each dyad/component then uses one radius for both participants.
            adaptive_summary_file = fullfile(CFG.output_path, ...
                'FaithfulAdaptiveMax',['Component_' num2str(which_comp)], ...
                ['FREQNESS_JRQA_VALIDATED_SUMMARY_Comp#' ...
                num2str(which_comp) '.mat']);
            adaptive_result = load(adaptive_summary_file, ...
                'Thresholds','specification','CFG');
            matching_settings = {'standardize','duration','original_srate', ...
                'target_srate','lowpass_cutoff','filter_order','metric_levels', ...
                'list_dyads','nconds','ntrials','radius_fraction'};
            for settingi = 1:numel(matching_settings)
                this_setting = matching_settings{settingi};
                assert(isequal(adaptive_result.CFG.(this_setting),CFG.(this_setting)), ...
                    'Adaptive radius source differs in CFG.%s.',this_setting);
            end
            specification.JRQA = adaptive_result.specification.JRQA;
            specification.JRQA.ThresholdMethod = 'radius';
            specification.JRQA.Aggregation = ...
                'median_dyad_radius_across_conditions_trials_and_metric_levels';
            specification.JRQA.Version = 'validated-v3-fixed-dyad-radius';
            specification.DyadRadii = nan(CFG.ndyads,1);
            for dyadi = CFG.list_dyads
                this_radius = adaptive_result.Thresholds(dyadi,:,:,:,1);
                assert(all(isfinite(this_radius) & this_radius > 0,'all'), ...
                    'Complete positive adaptive radii are required for dyad %d.',dyadi);
                specification.DyadRadii(dyadi) = median(this_radius,'all');
            end
            specification.RadiusSource = adaptive_summary_file;
        end

        result_size = [CFG.ndyads CFG.nconds nmeters CFG.ntrials];
        RR = nan(result_size);
        DET = nan(result_size);
        MarginalRR = nan([result_size CFG.nsubs]);
        Thresholds = nan([result_size CFG.nsubs]);

        for condi = 1:CFG.nconds
            for dyadi = CFG.list_dyads
                this_threshold = specification.threshold;
                if strcmp(specification.name,'FixedDyadRadius')
                    this_threshold = specification.DyadRadii(dyadi);
                end
                fprintf('%s JRQA: Component %d, Condition %d, Dyad %d\n', ...
                    specification.name,which_comp,condi,dyadi);
                for triali = 1:CFG.ntrials
                    output_file = fullfile(component_output_path,sprintf( ...
                        'FREQNESS_JRQA_VALIDATED_D%d_C%d_T%d.mat', ...
                        dyadi,condi,triali));
                    if isfile(output_file) && ~CFG.overwrite_flag
                        S = load(output_file,'FREQjrqa');
                        FREQjrqa = S.FREQjrqa;
                    else
                        input_file = fullfile(CFG.core_path,sprintf( ...
                            'FREQNESS_CORE_D%d_C%d_T%d.mat', ...
                            dyadi,condi,triali));
                        S = load(input_file,'GED','beat_frex');
                        FREQjrqa = FREQNESS_TimeCoord_Mocap( ...
                            S.GED,S.beat_frex,'method','jrqa', ...
                            'parameters',specification.JRQA, ...
                            'metric_levels',CFG.metric_levels, ...
                            'component',which_comp, ...
                            'duration',CFG.duration, ...
                            'srate',CFG.original_srate, ...
                            'target_srate',CFG.target_srate, ...
                            'lowpass_cutoff',CFG.lowpass_cutoff, ...
                            'filter_order',CFG.filter_order, ...
                            'standardize',CFG.standardize, ...
                            'threshold_method', ...
                            specification.threshold_method, ...
                            'threshold',this_threshold, ...
                            'theiler_window', ...
                            specification.theiler_window, ...
                            'lmin',CFG.lmin,'vmin',CFG.vmin, ...
                            'store_matrices',false);
                        save(output_file,'FREQjrqa','specification', ...
                            'which_comp','dyadi','condi','triali','CFG','-v7.3')
                    end

                    for metri = 1:nmeters
                        RR(dyadi,condi,metri,triali) = FREQjrqa(metri).RR;
                        DET(dyadi,condi,metri,triali) = FREQjrqa(metri).DET;
                        MarginalRR(dyadi,condi,metri,triali,:) = ...
                            reshape(FREQjrqa(metri).MarginalRR,1,1,1,1,[]);
                        Thresholds(dyadi,condi,metri,triali,:) = ...
                            reshape(FREQjrqa(metri).Thresholds,1,1,1,1,[]);
                    end
                end
            end
        end

        assert(all(isfinite(RR(CFG.list_dyads,:,:,:)),'all') && ...
            all(RR(CFG.list_dyads,:,:,:) > 0,'all'), ...
            '%s Component %d RR contains invalid values.', ...
            specification.name,which_comp);
        assert(all(isfinite(DET(CFG.list_dyads,:,:,:)),'all') && ...
            all(DET(CFG.list_dyads,:,:,:) > 0,'all'), ...
            '%s Component %d DET contains invalid values.', ...
            specification.name,which_comp);

        save(summary_file,'RR','DET','MarginalRR','Thresholds', ...
            'specification','which_comp','CFG','-v7.3')
    end
end


%% BLOCK 4 - R-READY EXPORTS FOR VALIDATED SPECIFICATIONS

visual_labels = ["No" "No" "Yes" "Yes"];
music_labels = ["Diff" "Same" "Diff" "Same"];
specification_names = { ...
    'CorrectedManuscript','Robustness','FaithfulAdaptiveMax','FixedDyadRadius'};

for specificationi = 1:numel(specification_names)
    specification_name = specification_names{specificationi};
    specification_statistics_path = fullfile( ...
        CFG.statistics_path,specification_name);
    if ~isfolder(specification_statistics_path)
        mkdir(specification_statistics_path)
    end

    for componenti = 1:numel(CFG.components)
        which_comp = CFG.components(componenti);
        summary_file = fullfile(CFG.output_path,specification_name, ...
            ['Component_' num2str(which_comp)], ...
            ['FREQNESS_JRQA_VALIDATED_SUMMARY_Comp#' ...
            num2str(which_comp) '.mat']);
        S = load(summary_file,'RR','DET');

        avg_RR = mean(S.RR(CFG.list_dyads,:,:,:),4);
        avg_DET = mean(S.DET(CFG.list_dyads,:,:,:),4);
        avg_RR = reshape(avg_RR, ...
            [numel(CFG.list_dyads) CFG.nconds nmeters]);
        avg_DET = reshape(avg_DET, ...
            [numel(CFG.list_dyads) CFG.nconds nmeters]);

        nrows = numel(CFG.list_dyads)*CFG.nconds*nmeters;
        dyad_col = zeros(nrows,1);
        visual_col = strings(nrows,1);
        music_col = strings(nrows,1);
        meter_col = strings(nrows,1);
        rr_col = zeros(nrows,1);
        det_col = zeros(nrows,1);

        rowi = 1;
        for dyad_idx = 1:numel(CFG.list_dyads)
            for condi = 1:CFG.nconds
                for metri = 1:nmeters
                    dyad_col(rowi) = CFG.list_dyads(dyad_idx);
                    visual_col(rowi) = visual_labels(condi);
                    music_col(rowi) = music_labels(condi);
                    meter_col(rowi) = "M" + string(metri);
                    rr_col(rowi) = avg_RR(dyad_idx,condi,metri);
                    det_col(rowi) = avg_DET(dyad_idx,condi,metri);
                    rowi = rowi+1;
                end
            end
        end

        output_table = table( ...
            dyad_col,visual_col,music_col,meter_col,rr_col,det_col, ...
            'VariableNames',{'Dyad','Visual','Music','Meter','RR','DET'});
        statistics_file = fullfile(specification_statistics_path, ...
            ['OUT2R_Comp#' num2str(which_comp) '.xlsx']);
        if ~isfile(statistics_file) || CFG.overwrite_flag
            writetable(output_table,statistics_file)
        end
    end
end


%% BLOCK 5 - STRATIFIED CIRCULAR-SHIFT COUPLING VALIDATION

% Use the primary fixed-dyad radius for observed and shifted recurrence plots.
% Partner 2 is circularly shifted while its recurrence geometry is preserved.
% Earlier robustness surrogates remain in their original output directory.
if CFG.surrogate_flag
    surrogate_output_path = fullfile( ...
        CFG.output_path,'SurrogateValidation',CFG.primary_specification);
    if ~isfolder(surrogate_output_path)
        mkdir(surrogate_output_path)
    end

    for componenti = 1:numel(CFG.components)
        which_comp = CFG.components(componenti);
        primary_summary_file = fullfile(CFG.output_path, ...
            CFG.primary_specification,['Component_' num2str(which_comp)], ...
            ['FREQNESS_JRQA_VALIDATED_SUMMARY_Comp#' num2str(which_comp) '.mat']);
        S = load(primary_summary_file,'specification');
        specification = S.specification;

        component_surrogate_path = fullfile( ...
            surrogate_output_path,['Component_' num2str(which_comp)]);
        if ~isfolder(component_surrogate_path)
            mkdir(component_surrogate_path)
        end

        result_size = [CFG.ndyads CFG.nconds nmeters CFG.ntrials];
        observed_rr = nan(result_size);
        observed_det = nan(result_size);
        null_rr_mean = nan(result_size);
        null_det_mean = nan(result_size);
        p_rr = nan(result_size);
        p_det = nan(result_size);
        z_rr = nan(result_size);
        z_det = nan(result_size);

        for condi = CFG.surrogate_conditions
            for dyadi = CFG.surrogate_dyads
                for triali = CFG.surrogate_trials
                    fprintf(['Surrogate JRQA: Component %d, Condition %d, ' ...
                        'Dyad %d, Trial %d\n'], ...
                        which_comp,condi,dyadi,triali);
                    surrogate_file = fullfile(component_surrogate_path, ...
                        sprintf('FREQNESS_JRQA_SURROGATE_D%d_C%d_T%d.mat', ...
                        dyadi,condi,triali));

                    if isfile(surrogate_file) && ~CFG.overwrite_flag
                        surrogate_result = load(surrogate_file, ...
                            'FREQjrqa','Surrogates');
                        FREQjrqa = surrogate_result.FREQjrqa;
                        Surrogates = surrogate_result.Surrogates;
                    else
                        input_file = fullfile(CFG.core_path,sprintf( ...
                            'FREQNESS_CORE_D%d_C%d_T%d.mat', ...
                            dyadi,condi,triali));
                        core_result = load(input_file,'GED','beat_frex');
                        random_seed = CFG.surrogate_random_seed+ ...
                            which_comp*100000+condi*1000+dyadi*10+triali;
                        [FREQjrqa,Surrogates] = ...
                            FREQNESS_JRQASurrogates_Mocap( ...
                            core_result.GED,specification.JRQA, ...
                            core_result.beat_frex, ...
                            'metric_levels',CFG.metric_levels, ...
                            'component',which_comp, ...
                            'duration',CFG.duration, ...
                            'srate',CFG.original_srate, ...
                            'target_srate',CFG.target_srate, ...
                            'lowpass_cutoff',CFG.lowpass_cutoff, ...
                            'filter_order',CFG.filter_order, ...
                            'standardize',CFG.standardize, ...
                            'threshold_method','radius', ...
                            'threshold',specification.DyadRadii(dyadi), ...
                            'theiler_window',specification.theiler_window, ...
                            'lmin',CFG.lmin,'vmin',CFG.vmin, ...
                            'n_surrogates',CFG.n_surrogates, ...
                            'random_seed',random_seed);
                        save(surrogate_file,'FREQjrqa','Surrogates', ...
                            'specification','random_seed','which_comp', ...
                            'dyadi','condi','triali','CFG','-v7.3')
                    end

                    for metri = 1:nmeters
                        observed_rr(dyadi,condi,metri,triali) = ...
                            FREQjrqa(metri).RR;
                        observed_det(dyadi,condi,metri,triali) = ...
                            FREQjrqa(metri).DET;
                        null_rr_mean(dyadi,condi,metri,triali) = ...
                            mean(Surrogates(metri).RR);
                        null_det_mean(dyadi,condi,metri,triali) = ...
                            mean(Surrogates(metri).DET);
                        p_rr(dyadi,condi,metri,triali) = ...
                            Surrogates(metri).PValueRR;
                        p_det(dyadi,condi,metri,triali) = ...
                            Surrogates(metri).PValueDET;
                        z_rr(dyadi,condi,metri,triali) = ...
                            Surrogates(metri).ZScoreRR;
                        z_det(dyadi,condi,metri,triali) = ...
                            Surrogates(metri).ZScoreDET;
                    end
                end
            end
        end

        summary_file = fullfile(component_surrogate_path, ...
            ['FREQNESS_JRQA_SURROGATE_SUMMARY_Comp#' ...
            num2str(which_comp) '.mat']);
        save(summary_file,'observed_rr','observed_det','null_rr_mean', ...
            'null_det_mean','p_rr','p_det','z_rr','z_det', ...
            'specification','CFG','-v7.3')

        [dyad_grid,condition_grid,meter_grid,trial_grid] = ndgrid( ...
            CFG.surrogate_dyads,CFG.surrogate_conditions, ...
            1:nmeters,CFG.surrogate_trials);
        linear_idx = sub2ind(result_size,dyad_grid(:), ...
            condition_grid(:),meter_grid(:),trial_grid(:));
        surrogate_table = table( ...
            dyad_grid(:),condition_grid(:),trial_grid(:), ...
            meter_grid(:),reshape( ...
            CFG.metric_levels(meter_grid(:)),[],1), ...
            observed_rr(linear_idx),null_rr_mean(linear_idx), ...
            p_rr(linear_idx),z_rr(linear_idx), ...
            observed_det(linear_idx),null_det_mean(linear_idx), ...
            p_det(linear_idx),z_det(linear_idx), ...
            'VariableNames',{'Dyad','Condition','Trial','MeterIndex', ...
            'MetricLevel','ObservedRR','NullRRMean','PValueRR','ZScoreRR', ...
            'ObservedDET','NullDETMean','PValueDET','ZScoreDET'});
        writetable(surrogate_table,fullfile(component_surrogate_path, ...
            ['FREQNESS_JRQA_SURROGATE_SUMMARY_Comp#' ...
            num2str(which_comp) '.csv']))
